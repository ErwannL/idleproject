const rx = (src) => new RegExp(src.replaceAll('#', NUM));
// Virgule décimale française → point anglais.
export { num };
// Durées : « 4 h 05 min » → « 4h 05m », « 5 min 03 s » → « 5m 03s », « 3 j » → « 3d ».
export function dur(s) {
  return String(s)
    .replace(/(\d+) h (\d+) min\b/g, '$1h $2m')
    .replace(/(\d+) min (\d+) s\b/g, '$1m $2s')
    .replace(/(\d+) h (\d\d)\b/g, '$1h $2m')
    .replace(/(\d+) j\b/g, '$1d')
    .replace(/(\d+) h\b/g, '$1h')
    .replace(/(\d+) s\b/g, '$1s');
}
const pl = (n, one, many) => (Number(String(n).replace(/[^\d.-]/g, '')) === 1 ? one : many);
